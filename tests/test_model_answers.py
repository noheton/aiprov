"""Several models behind one answer: role, fallback, routing rule, judge and score (issue 9)."""
import pathlib, shutil, subprocess, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
BAD = ROOT / "tests" / "fixtures" / "model-answers-bad.ttl"
BASE = "https://example.org/prov/"


def run(args, cwd):
    return subprocess.run([sys.executable, "-m", "aiprov.provlog", "--base", BASE, *args], cwd=cwd,
                          capture_output=True, text=True, check=False)


def ok(args, cwd):
    r = run(args, cwd)
    assert r.returncode == 0, r.stdout + r.stderr
    return r


def setup(tmp_path):
    ok(["init"], tmp_path)
    ok(["agent", "--id", "big", "--type", "ai", "--model", "m-big"], tmp_path)
    ok(["agent", "--id", "small", "--type", "ai", "--model", "m-small"], tmp_path)
    ok(["agent", "--id", "judge", "--type", "ai", "--model", "m-judge"], tmp_path)


def test_fallback_after_an_error(tmp_path):
    setup(tmp_path)
    ok(["log", "--activity", "try1", "--agent", "big", "--model-role", "answer", "--routed-by", "cheapest-first"], tmp_path)
    ok(["log", "--activity", "try2", "--agent", "small", "--model-role", "answer", "--fallback-of", "try1",
        "--fallback-reason", "timeout", "--generated", "reply.md"], tmp_path)
    assert ok(["validate"], tmp_path).returncode == 0
    rep = ok(["report"], tmp_path).stdout
    assert "-- model answers --" in rep and "final: small (m-small)" in rep and "fallbacks: 1 (timeout 1)" in rep
    ttl = (tmp_path / "provenance.ttl").read_text(encoding="utf-8")
    assert "fallbackOf" in ttl and "routedBy" in ttl and "plan-cheapest-first" in ttl


def test_draft_and_revise_pair(tmp_path):
    setup(tmp_path)
    ok(["log", "--activity", "d1", "--agent", "small", "--model-role", "draft", "--generated", "draft.md"], tmp_path)
    ok(["log", "--activity", "r1", "--agent", "big", "--model-role", "revise", "--generated", "final.md"], tmp_path)
    assert ok(["validate"], tmp_path).returncode == 0
    rep = ok(["report"], tmp_path).stdout
    assert "final-md" in rep and "final: big (m-big)" in rep and "draft-md" not in rep


def test_judged_answer(tmp_path):
    setup(tmp_path)
    ok(["log", "--activity", "a1", "--agent", "big", "--model-role", "answer", "--generated", "reply.md"], tmp_path)
    ok(["log", "--activity", "j1", "--agent", "judge", "--model-role", "judge", "--judges", "reply.md",
        "--score", "0.8"], tmp_path)
    assert ok(["validate"], tmp_path).returncode == 0
    assert "judged answers: 1" in ok(["report"], tmp_path).stdout
    ttl = (tmp_path / "provenance.ttl").read_text(encoding="utf-8")
    assert "scoreValue" in ttl and "score-j1" in ttl


def test_log_refuses_what_makes_no_sense(tmp_path):
    setup(tmp_path)
    ok(["log", "--activity", "a1", "--agent", "big", "--generated", "reply.md"], tmp_path)
    ttl = tmp_path / "provenance.ttl"
    before = ttl.read_bytes()
    for args, msg in (
        (["--fallback-of", "ghost"], "is not logged"),
        (["--fallback-of", "x"], "cannot be the fallback of itself"),
        (["--fallback-reason", "error"], "needs --fallback-of"),
        (["--judges", "reply.md"], "belong together"),
        (["--score", "1"], "belong together"),
        (["--judges", "nothing.md", "--score", "1"], "not the output of a logged activity"),
        (["--judges", "reply.md", "--score", "high"], "not a number"),
    ):
        r = run(["log", "--activity", "x", "--agent", "small", *args], tmp_path)
        assert r.returncode != 0 and msg in (r.stdout + r.stderr), (args, r.stdout, r.stderr)
        assert ttl.read_bytes() == before, args  # a refused call leaves the graph untouched


def test_validator_catches_a_hand_edited_graph(tmp_path):
    shutil.copy(BAD, tmp_path / "provenance.ttl")
    r = run(["validate"], tmp_path)
    assert r.returncode == 1
    assert "[FAIL] entities generated by two activities that carry a model role: 1" in r.stdout
    assert "[FAIL] fallbackOf targets that are not other logged activities: 2" in r.stdout


def test_legacy_graph_is_unchanged(tmp_path):
    setup(tmp_path)
    ok(["log", "--activity", "plain", "--agent", "big", "--generated", "a.md"], tmp_path)
    ok(["log", "--activity", "again", "--agent", "small", "--generated", "a.md"], tmp_path)  # same file twice: legacy practice
    assert ok(["validate"], tmp_path).returncode == 0
    assert "-- model answers --" not in ok(["report"], tmp_path).stdout
